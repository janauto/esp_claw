-- 持久化：FAT 语义下的原子写、.tmp 恢复、坏文件另存 .bad、目录列表
local H = dofile("helper.lua")
local root = H.tmpdir()
local env = H.env(root)
local store = require("core.store").new(env)

H.case("数据目录在 <DATA>/garden 下", function()
  H.eq(store.base, root .. "/garden"); H.eq(store.paths.snapshot, root .. "/garden/snapshot.json")
end)
H.case("首次读取：new", function()
  local d, st = store.load_garden()
  H.eq(d, nil); H.eq(st, "new")
end)
H.case("保存后读回；重复保存也能覆盖（FAT 不能覆盖式 rename：先删旧文件）", function()
  H.ok(store.save_garden({ v = 1, pet = { name = "小磁" } }))
  H.ok(store.save_garden({ v = 1, pet = { name = "豆豆" } }))
  local d, st = store.load_garden()
  H.eq(st, "ok"); H.eq(d.pet.name, "豆豆")
  H.eq(env.storage.exists(store.paths.garden .. ".tmp"), false, ".tmp 应该已经改名")
end)
H.case("覆盖途中被停止（只剩 .tmp）：用 .tmp 恢复", function()
  os.remove(store.paths.garden)
  env.storage.write_file(store.paths.garden .. ".tmp", '{"v":1,"pet":{"name":"团子"}}')
  local d, st = store.load_garden()
  H.eq(st, "recovered"); H.eq(d.pet.name, "团子")
  os.remove(store.paths.garden .. ".tmp")
end)
H.case("正式文件损坏：另存 .bad、返回 reset，不悄悄丢数据", function()
  env.storage.write_file(store.paths.garden, '{"v":1,"pet":')
  local d, st = store.load_garden()
  H.eq(d, nil); H.eq(st, "reset")
  H.eq(env.storage.read_file(store.paths.garden .. ".bad"), '{"v":1,"pet":')
end)
H.case("列目录：只要指定后缀、按名字排序、补上大小", function()
  store.ensure_dirs()
  env.storage.write_file(store.paths.plants .. "/b.lua", "return {}")
  env.storage.write_file(store.paths.plants .. "/a.lua", "return { name = 'a' }")
  env.storage.write_file(store.paths.plants .. "/note.txt", "x")
  local l = store.list(store.paths.plants, ".lua")
  H.eq(#l, 2); H.eq(l[1].name, "a.lua"); H.eq(l[1].size, #"return { name = 'a' }")
end)
os.execute("rm -rf '" .. root .. "'")
H.finish("持久化")
