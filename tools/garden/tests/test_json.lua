-- JSON：编码稳定（键排序）、转义、中文、数组/对象、坏输入
local H = dofile("helper.lua")
local J = require("core.json")

H.case("对象键按字典序输出，同样的数据得到同样的文本", function()
  H.eq(J.encode({ b = 1, a = { 2, 3 }, c = "x" }), '{"a":[2,3],"b":1,"c":"x"}')
end)
H.case("转义与中文原样保留", function()
  local s = J.encode({ t = 'a"b\\c\n小磁' })
  H.eq(s, '{"t":"a\\"b\\\\c\\n小磁"}')
  H.eq(J.decode(s).t, 'a"b\\c\n小磁')
end)
H.case("数字：整数不带小数点，浮点保留精度，NaN 写成 null", function()
  H.eq(J.encode({ 1, 2.5, 3.0, 0 / 0 }), "[1,2.5,3,null]")
end)
H.case("往返：嵌套表", function()
  local v = { v = 1, pet = { name = "小磁", mood = 72.5, daily = { date = "2026-10-15", cups = 3 } }, plots = { { uid = 1, seed = "water", state = {} } } }
  local back = J.decode(J.encode(v))
  H.eq(back.pet.name, "小磁"); H.eq(back.pet.daily.cups, 3); H.eq(back.plots[1].seed, "water"); H.eq(math.type(back.plots[1].uid), "integer")
end)
H.case("\\u 转义与代理对", function()
  H.eq(J.decode('"\\u5c0f\\u78c1"'), "小磁")
  H.eq(J.decode('"\\ud83d\\ude00"'), utf8.char(0x1F600))
end)
H.case("坏输入返回 nil 和原因，不抛错", function()
  local v, err = J.decode('{"a":1,')
  H.eq(v, nil); H.ok(err and err:find("json"), "要有原因")
  H.eq(J.decode("[1,2]x"), nil)
  H.eq(J.decode(nil), nil)
end)
H.case("函数、userdata 不会写坏输出", function()
  H.eq(J.encode({ a = print, b = 1 }), '{"b":1}')
end)
H.finish("JSON")
